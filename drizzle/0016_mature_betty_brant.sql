-- A metric key has one durable meaning and unit for an account. The advisory
-- lock closes the first-insert race across replicas; the trigger protects the
-- invariant even if a future writer bypasses the TypeScript service.
DO $measurement_preflight$
BEGIN
	IF EXISTS (
		SELECT 1
		FROM "measurements"
		GROUP BY "user_id", "metric_key"
		HAVING count(DISTINCT "label") > 1 OR count(DISTINCT "unit") > 1
	) THEN
		RAISE EXCEPTION '0016 preflight: a measurement key has conflicting labels or units';
	END IF;
END
$measurement_preflight$;--> statement-breakpoint
CREATE OR REPLACE FUNCTION "enforce_measurement_definition"()
RETURNS trigger
LANGUAGE plpgsql
AS $measurement_definition$
BEGIN
	PERFORM pg_advisory_xact_lock(
		hashtextextended(
			'measurement-definition:' || NEW."user_id"::text || ':' || NEW."metric_key",
			0
		)
	);
	IF EXISTS (
		SELECT 1
		FROM "measurements" existing
		WHERE
			existing."user_id" = NEW."user_id"
			AND existing."metric_key" = NEW."metric_key"
			AND existing."id" <> NEW."id"
			AND (
				existing."label" IS DISTINCT FROM NEW."label"
				OR existing."unit" IS DISTINCT FROM NEW."unit"
			)
	) THEN
		RAISE EXCEPTION USING
			ERRCODE = '23514',
			CONSTRAINT = 'measurements_definition_consistency',
			MESSAGE = 'measurement key label/unit conflicts with its existing definition';
	END IF;
	RETURN NEW;
END
$measurement_definition$;--> statement-breakpoint
CREATE TRIGGER "measurements_definition_consistency_trigger"
BEFORE INSERT OR UPDATE OF "user_id", "metric_key", "label", "unit"
ON "measurements"
FOR EACH ROW
