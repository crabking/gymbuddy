DO $calendar_preflight$
BEGIN
	IF EXISTS (
		SELECT 1
		FROM "program_days"
		WHERE CASE
			WHEN "date" ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
				THEN to_char(to_date("date", 'YYYY-MM-DD'), 'YYYY-MM-DD') <> "date"
			ELSE true
		END
	) THEN
		RAISE EXCEPTION '0016 preflight: invalid program calendar date';
	END IF;
	IF EXISTS (
		SELECT 1
		FROM "programs"
		WHERE
			CASE
				WHEN
					"start_date" ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
					AND "end_date" ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
				THEN
					to_char(to_date("start_date", 'YYYY-MM-DD'), 'YYYY-MM-DD') <> "start_date"
					OR to_char(to_date("end_date", 'YYYY-MM-DD'), 'YYYY-MM-DD') <> "end_date"
					OR "end_date" < "start_date"
				ELSE true
			END
	) THEN
		RAISE EXCEPTION '0016 preflight: invalid program start/end date';
	END IF;
	IF EXISTS (
		SELECT 1
		FROM "workout_sessions"
		WHERE CASE
			WHEN "session_date" ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
				THEN to_char(to_date("session_date", 'YYYY-MM-DD'), 'YYYY-MM-DD') <> "session_date"
			ELSE true
		END
	) THEN
		RAISE EXCEPTION '0016 preflight: invalid workout session date';
	END IF;
END
